"""Blocks of the branch predictor (gshare with a branch target buffer), one per core: the table block in the fetch stage, the side registers that carry
a prediction with its instruction to the execute stage, and the resolution in the execute stage. Generated by BARG against hand-written golden models
(golden/<name>.py), never shown to the generator. How they join the core: demos/linux-soc/build_core.py --bp."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "gpu-soc"))
from build_gpu_soc import block, i, o, port  # noqa: E402

W = 32
CLK = port("p_clk", "clk", "in", 1, "clock")
RST = port("p_rst", "rst", "in", 1, "reset")

GSHARE_TBL = block("b_gshare_tbl", "gshare_tbl", """
    Branch predictor tables of one core, in the fetch stage: a gshare direction predictor and a branch target buffer. Held state: ghr (8 bits, the global
    history of conditional branch outcomes, newest in bit 0); pht, 256 two-bit saturating counters; btb, 32 entries, each with valid (1 bit), tag (26 bits),
    target (32 bits) and jump (1 bit). At reset ghr is 0, every pht counter is 1 and every btb entry is invalid. Lookup, combinational from the held state and
    pc (32 bits, the address being fetched, always even): idx (8 bits) is bits 8:1 of pc exclusive-or ghr; bi (5 bits) is bits 5:1 of pc; hit is 1 when btb
    entry bi is valid and its tag equals bits 31:6 of pc. pred_taken is hit AND (jump of entry bi OR bit 1 of pht[idx]); pred_target is target of entry bi
    (0 when hit is 0); pred_idx is idx; pred_redirect is pred_taken AND NOT stall (stall is 1 while the fetch stage holds). Update, on each rising clock edge
    after reset, when upd_en is 1: when upd_cond is 1, pht[upd_idx] counts up by one (saturating at 3) when upd_taken is 1 and down by one (saturating at 0)
    when it is 0, and ghr becomes ghr shifted left by one (its top bit dropped) with upd_taken in bit 0; and, whether upd_cond is 1 or 0, when upd_taken is
    1, btb entry number bits 5:1 of upd_pc becomes valid with tag bits 31:6 of upd_pc, target upd_target (32 bits) and jump upd_jump. When upd_en is 0 nothing
    changes.
""", [CLK, RST, i("pc", W, "addr"), i("stall", 1, "control"), i("upd_en", 1, "control"), i("upd_idx", 8, "control"), i("upd_taken", 1, "control"),
      i("upd_cond", 1, "control"), i("upd_jump", 1, "control"), i("upd_pc", W, "addr"), i("upd_target", W, "addr"), o("pred_taken", 1, "control"),
      o("pred_redirect", 1, "control"), o("pred_target", W, "addr"), o("pred_idx", 8, "control")], reset="sync", latency=1)

BP_PIPE = block("b_bp_pipe", "bp_pipe", """
    Carries the prediction made for an instruction in the fetch stage along with it to the execute stage: two register stages, like the pipeline registers
    they follow. Fetch to decode (the *_id values): on each rising clock edge, when rst is 1 or flush_if is 1 they become 0; otherwise when stall_if is 1 they
    keep their value; otherwise they become pt_if (1 bit), ptarget_if (32 bits) and pidx_if (8 bits). Decode to execute (the *_ex values): when rst is 1 or
    flush_id is 1 they become 0; otherwise when stall_id is 1 they keep their value; otherwise they become the *_id values (held before the edge). Every
    output is the held value of the register of that name, with no combinational path from an input to an output.
""", [CLK, RST, i("stall_if", 1, "control"), i("flush_if", 1, "control"), i("stall_id", 1, "control"), i("flush_id", 1, "control"), i("pt_if", 1, "control"),
      i("ptarget_if", W, "addr"), i("pidx_if", 8, "control"), o("pt_ex", 1, "control"), o("ptarget_ex", W, "addr"), o("pidx_ex", 8, "control")],
    reset="sync", latency=1)

BP_RESOLVE = block("b_bp_resolve", "bp_resolve", """
    Branch resolution in the execute stage. pcsel (2 bits) is the instruction's next-address choice: 00 next, 01 conditional branch, 10 jump, 11 register jump.
    br_redirect and br_pc (32 bits) are the branch unit's decision: whether the instruction leaves the sequential path and where to. valid is 1 for a real
    instruction. pc_plus4 (32 bits) is the address of the sequential next instruction. pt, ptarget (32 bits) and pidx (8 bits) are the prediction made for the
    instruction in the fetch stage. actual is valid AND br_redirect. mispredict is valid AND (pt differs from actual, or actual is 1 and ptarget differs from
    br_pc). redirect is mispredict; redirect_pc is br_pc when actual is 1 and pc_plus4 when actual is 0. upd_en is valid AND pcsel is not 00; upd_idx is pidx;
    upd_taken is actual; upd_cond is 1 when pcsel is 01; upd_jump is 1 when pcsel is 10 or 11. No clock, no reset, no state.
""", [i("pcsel", 2, "control"), i("br_redirect", 1, "control"), i("br_pc", W, "addr"), i("valid", 1, "control"), i("pc_plus4", W, "addr"), i("pt", 1, "control"),
      i("ptarget", W, "addr"), i("pidx", 8, "control"), o("redirect", 1, "control"), o("redirect_pc", W, "addr"), o("upd_en", 1, "control"),
      o("upd_idx", 8, "control"), o("upd_taken", 1, "control"), o("upd_cond", 1, "control"), o("upd_jump", 1, "control")])

BP_OR = block("b_bp_or", "bp_or", """
    Combinational. y is a OR b. No clock, no reset, no state.
""", [i("a", 1, "control"), i("b", 1, "control"), o("y", 1, "control")])

BP_MUX = block("b_bp_mux", "bp_mux", """
    Combinational. y (32 bits) is from_fp when sel is 1 and from_alu when sel is 0. No clock, no reset, no state.
""", [i("from_alu", W, "addr"), i("from_fp", W, "addr"), i("sel", 1, "control"), o("y", W, "addr")])

BLOCKS = [GSHARE_TBL, BP_PIPE, BP_RESOLVE, BP_OR, BP_MUX]

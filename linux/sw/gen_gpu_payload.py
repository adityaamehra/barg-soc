#!/usr/bin/env python3
"""Makes sw/gpu_payload.h for init.c's `gpu` command: the GPU program that draws one scene (the triangle rasteriser of demos/simt-gpu/gfx plus the
scene's data), as (offset, word) writes into the GPU window (offsets from 0x3000_0000), the depth clear, the start address, and the checksum of the
finished frame (s = s*31 + word over the frame's 38,400 words) that the frame model says the GPU must leave in video memory.

    python3 demos/linux-soc/sw/gen_gpu_payload.py [scene] [out.h]        # default: gouraud, sw/gpu_payload.h
"""
import subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "demos" / "gpu-soc"))
import gpu_tests as gt  # noqa: E402  (puts demos/simt-gpu and its gfx folder on the path)
import run_kernel, scenes, run_g2a  # noqa: E402,E401

M = 0xFFFFFFFF
BASE = 0x30000000
scene = sys.argv[1] if len(sys.argv) > 1 else "gouraud"
out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).with_name("gpu_payload.h")
work = Path("/tmp/gpu-payload-work"); work.mkdir(exist_ok=True)
elf = work / "tri_rast.elf"
subprocess.run([run_kernel.GCC, *run_kernel.CFLAGS, "-T", str(gt.GPU / "sw" / "link.ld"), str(gt.GPU / "sw" / "crt0.S"),
                str(gt.GPU / "gfx" / "sw" / "tri_rast.c"), "-o", str(elf)], check=True)
import simt  # noqa: E402
syms = run_kernel.load_elf(simt.Gpu(simt.Config()), elf)
clear, tris = scenes.scene(scene)
tex, zclear = scenes.texture(scene), scenes.depth_clear(scene)
want = scenes.frame(clear, tris, tex, zclear)
data = run_g2a.scene_bytes(syms, clear, tris, tex, None)
wr = [w for a, seg in gt.cp.elf_segments(elf) for w in gt.words(a, seg)]
wr += [w for a, raw in data.items() for w in gt.words(a, raw)]
wr = [(gt.soc_addr(a) - BASE, v) for a, v in wr]
fills = [] if zclear is None else [(gt.soc_addr(0x4004_0000) - BASE, 320 * 240 // 2, zclear << 16 | zclear)]
s = 0
for p in range(0, 320 * 240, 2):
    s = (s * 31 + (want[p + 1] << 16 | want[p])) & M
rows = ",".join("{0x%xu,0x%xu}" % (a, v & M) for a, v in wr)
fil = ",".join("{0x%xu,%du,0x%xu}" % f for f in fills) or "{0,0,0}"
out.write_text(f"""/* generated by gen_gpu_payload.py: scene {scene}; the GPU program and data as (offset from 0x30000000, word) writes */
#define GPU_SCENE "{scene}"
static const u32 GPU_WR[][2] = {{{rows}}};
#define GPU_N_WR {len(wr)}
static const u32 GPU_FIL[][3] = {{{fil}}};
#define GPU_N_FIL {len(fills)}
#define GPU_START {syms["_start"][0]:#x}u
#define GPU_FRAME_OFF {gt.soc_addr(0x4000_0000) - BASE:#x}u
#define GPU_FRAME_WORDS {320 * 240 // 2}u
#define GPU_SUM_WANT {s:#x}u
""")
print(f"{out}: scene {scene}, {len(wr)} words, {len(fills)} fills, frame checksum {s:#x}")

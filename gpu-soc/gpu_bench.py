"""The generated Verilog of the GPU SoC (`gpu-soc`, demos/gpu-soc/design.json), assembled for the SoC bench (demos/nuttx-soc/soc_bench.py).

    sources() -> {block name: Verilog}, manifest      soc() -> soc_bench.Soc on design.json with those sources

Where each block's RTL comes from (nothing is written by hand):
  * the SoC's blocks: the newest finished job of the stage-4 design (`nuttx-soc-imac-16mb`) in `workspace/` or `workspace-mistral/`
    (blocks were spread over two backends and several models to shorten the wall time);
  * region_decode, bus_ctl, io_mux, gpu_bridge: the newest finished job of `gpu-soc` in `workspace-mistral/` whose module agrees with
    its golden model (demos/gpu-soc/golden/, checked here under Icarus);
  * the GPU's blocks: demos/simt-gpu/gfx/rtl/<name>.v, else demos/simt-gpu/rtl/<name>.v (the GPU core's), with only the module
    line renamed to g_<name>.
"""

from __future__ import annotations

import importlib.util
import json
import os
import re
import sqlite3
import sys
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
SOC_DIR = ROOT / "demos" / "nuttx-soc"
GPU_RTL, CORE_RTL = ROOT / "demos" / "simt-gpu" / "gfx" / "rtl", ROOT / "demos" / "simt-gpu" / "rtl"
STAGE4, STAGE4_WS = SOC_DIR / "design-a-16mb.json", ROOT / "workspace"
G3_WS = ROOT / "workspace-mistral"
G3_BLOCKS = ("region_decode", "bus_ctl", "io_mux", "gpu_bridge")

_spec = importlib.util.spec_from_file_location("soc_bench", SOC_DIR / "soc_bench.py")
sb = importlib.util.module_from_spec(_spec)
sys.modules["soc_bench"] = sb
_spec.loader.exec_module(sb)
sys.path.insert(0, str(HERE))
import check_golden_local  # noqa: E402


def _jobs(ws: Path, design_id: str, block_id: str) -> list[str]:
    db = sqlite3.connect(ws / "jobs.sqlite")
    return [r[0] for r in db.execute("select id from jobs where design_id=? and block_id=? and state='done' order by created_at desc",
                                     (design_id, block_id))]


RANK = {"VERIFIED": 0, "VERIFIED_LOWCONF": 1, "REVIEW": 2}


def _newest(design_id: str, block_id: str) -> Path | None:
    """delivered.v of a block's best finished job across the SoC workspaces: the best verdict, then the newest (a block may have
    been generated by several models at once; a REVIEW that came last must not replace a VERIFIED)."""
    rows = []
    for ws in (STAGE4_WS, G3_WS):
        db = sqlite3.connect(ws / "jobs.sqlite")
        rows += [(RANK.get(v, 3), c, ws / design_id / "jobs" / i / "delivered.v") for i, v, c in db.execute(
            "select id, verdict, created_at from jobs where design_id=? and block_id=? and state='done'", (design_id, block_id))]
    rows.sort(key=lambda r: (r[0], [-ord(ch) for ch in r[1]]))
    return rows[0][2] if rows else None


def sources() -> tuple[dict[str, str], dict]:
    design = json.loads((HERE / "design.json").read_text())
    stage4 = json.loads(STAGE4.read_text())
    out, manifest = {}, {}
    soc_ids = {b["id"] for b in stage4["blocks"]}
    for b in design["blocks"]:
        name = b["name"]
        if name in G3_BLOCKS:
            for job in _jobs(G3_WS, "gpu-soc", b["id"]):
                f = G3_WS / "gpu-soc" / "jobs" / job / "delivered.v"
                bad, total, first = check_golden_local.check(name, f)
                if not bad:
                    out[name], manifest[name] = f.read_text(), {"from": f"gpu-soc job {job}", "golden": f"agrees on all {total}"}
                    break
            else:
                raise SystemExit(f"{name}: no generation agrees with its golden model yet")
        elif b["id"] in soc_ids:
            f = _newest(stage4["id"], b["id"])
            if f is None:
                raise SystemExit(f"{name}: no finished stage-4 job")
            out[name] = f.read_text()
            manifest[name] = {"from": str(f.relative_to(ROOT))}
        else:
            assert name.startswith("g_"), name
            src = GPU_RTL / f"{name[2:]}.v"
            src = src if src.exists() else CORE_RTL / f"{name[2:]}.v"
            text, n = re.subn(rf"\bmodule\s+{re.escape(name[2:])}\b", f"module {name}", src.read_text(), count=1)
            assert n == 1, f"no module {name[2:]} in {src}"
            out[name], manifest[name] = text, {"from": str(src.relative_to(ROOT)), "renamed": f"{name[2:]} -> {name}"}
    return out, manifest


def soc() -> "sb.Soc":
    hier = os.environ.get("GPU_SOC_HIER")
    if hier:
        return soc_hier(Path(hier))
    srcs, _ = sources()
    return sb.Soc(HERE / "design.json", STAGE4_WS, overrides=srcs)


def soc_hier(flat: Path) -> "sb.Soc":
    """The GPU SoC built from IPs (design-hier.json), flattened by `node packages/backend/dist/cli/ip.js flatten ... --out <flat>`:
    every block from an IP takes the Verilog the IP library stored (<flat>/sources/<module>.v); the one block that is not in an IP
    (gpu_bridge) takes the same generation as the flat design."""
    design = json.loads((flat / "design.json").read_text())
    srcs, _ = sources()
    out = {}
    for b in design["blocks"]:
        f = flat / "sources" / f"{b['moduleName']}.v"
        out[b["name"]] = f.read_text() if f.exists() else srcs[b["name"]]
    return sb.Soc(flat / "design.json", STAGE4_WS, overrides=out)


if __name__ == "__main__":
    s, m = sources()
    print(f"{len(s)} blocks: {sum(1 for v in m.values() if 'renamed' in v)} GPU (renamed), "
          f"{sum(1 for k in m if k in G3_BLOCKS)} new or changed for G3, the rest from the stage-4 SoC")
